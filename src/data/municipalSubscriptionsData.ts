export function getOrCreateMunicipalSubscription(
  cityName: string,
  municipalityName?: string,
  lat?: number,
  lng?: number
): MunicipalCitySubscription {
  const normCity = cityName.trim();
  const cityKey = normCity.toLowerCase().replace(/[^a-z0-9]/g, '');

  const existing = INITIAL_MUNICIPAL_CITY_SUBSCRIPTIONS.find(
    (s) => s.cityKey === cityKey || s.cityName.toLowerCase() === normCity.toLowerCase()
  );

  if (existing) {
    return existing;
  }

  const newSub: MunicipalCitySubscription = {
    id: `sub-${cityKey}-gov`,
    cityKey,
    cityName: normCity,
    country: 'International',
    flagEmoji: '🌐',
    latitude: lat || 33.5651,
    longitude: lng || 73.0169,
    municipalityName: municipalityName || `${normCity} Municipal Corporation & Public Works`,
    planTier: 'Enterprise Gov Desk ($1,250/mo)',
    mrr: 1250,
    annualBilling: '$15,000 / yr',
    status: 'ACTIVE',
    subscribedSince: new Date().toISOString(),
    renewalDate: new Date(Date.now() + 365 * 24 * 3600 * 1000).toISOString(),
    slaTier: 'Gold 99.9% 1-Hour Response',
    contactLead: `operations@${cityKey}.civicgov.org`,
    seatsAssigned: 35,
    activeDispatchersCount: 2,
    activeDispatcheesCount: 10,
    subscribedDepartments: [
      'Department of Public Works (DPW)',
      'Water & Sanitation Agency',
      'Public Lighting & Traffic Signals',
      'Environmental Health & Refuse',
    ],
    zonesCovered: [`${normCity} Central Ward`, `${normCity} Commercial District`, `${normCity} North Sub-division`],
    isGeotagged: true,
    poNumber: `PO-${new Date().getFullYear()}-${cityKey.toUpperCase()}-AUTO`,
  };

  return newSub;
}
